"""Generate the reference documents from configuration and results (nothing in them is typed by hand):

    docs/COMPANY_MAPPING.md   company mapping database (links + cited profiles)
    docs/INDICATORS.md        indicator registry with coverage
    docs/SOURCES_TABLE.md     source registry table (included from DATA_SOURCES.md)
    docs/RESULTS.md           every result table in out/
"""
from __future__ import annotations

