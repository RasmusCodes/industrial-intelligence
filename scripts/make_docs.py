import sys
from pathlib import Path

import pandas as pd
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from indintel import store  # noqa: E402
from indintel.indicators_config import registry  # noqa: E402
from indintel.mapping import companies, load_profiles  # noqa: E402
from indintel.paths import CONFIG, DOCS, OUT  # noqa: E402
from indintel.universe import raw as uraw  # noqa: E402

GEN = "<!-- generated by scripts/make_docs.py; edit the configuration, not this file -->\n\n"
MODEL = {"RW": "Random walk", "AR": "History only (AR)", "Composite": "Indicator composite",
         "BayesComp": "Indicators, partially pooled", "MappedRidge": "Indicators, ridge", "GBM": "Gradient boosting",
         "BacklogAR": "Backlog growth", "Conversion": "Backlog conversion", "PriceCost": "Price-cost"}


def md_table(df: pd.DataFrame, floatfmt: dict | None = None) -> str:
    floatfmt = floatfmt or {}
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        cells = []
        for c, v in zip(cols, r):
            if isinstance(v, float):
                f = floatfmt.get(c, "{:.3f}")
                cells.append("" if pd.isna(v) else f.format(v))
            else:
                cells.append("" if v is None or (isinstance(v, float) and pd.isna(v)) else str(v).replace("|", "/"))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def company_mapping() -> None:
    u = uraw()
    names = {r["ticker"]: r["name"] for r in u["targets"] + u.get("annual_only", []) + u.get("mapping_only", [])}
    reg = {r["id"]: r for r in registry()}
    profs = load_profiles()
    texts = store.load("annual_texts", missing_ok=True)
    url = dict(zip(texts["path"], texts["url"])) if not texts.empty else {}
    parts = [GEN, "# Company mapping database\n\n",
             "Two layers. **Links** (config/companies.yaml): which operational indicators drive which company, segment "
             "and line item, with the expected timing and the channel, written before any model was fitted. "
             "**Profiles** (config/profiles/): segments, geographic exposure, customers, backlog, pricing and margin "
             "drivers, each supported by sentences quoted from the company's latest annual report. Every quote is "
             "checked against the filing text by `python -m indintel verify-mapping` and the test suite.\n\n"]
    for c in companies():
        tk = c["ticker"]
        parts.append(f"## {names.get(tk, tk)} ({tk})\n\n")
        p = profs.get(tk)
        if p:
            parts.append(f"{p.get('description', '')}\n\n")
            doc = p.get("document")
            if doc in url:
                parts.append(f"Source: [{doc.split('_')[1]} filed {doc.rsplit('_', 1)[1][:-4]}]({url[doc]})\n\n")
            if p.get("segments"):
                parts.append("**Segments**\n\n" + "".join(f"- **{s['name']}**: {s['sells']}. Demand: {s['end_markets']}\n"
                                                          for s in p["segments"]) + "\n")
            for f, title in (("geography", "Geographic exposure"), ("customers", "Customers"), ("backlog", "Order backlog"),
                             ("pricing", "Pricing dynamics"), ("margin_drivers", "Margin drivers")):
                b = p.get(f) or {}
                parts.append(f"**{title}.** {b.get('summary', '')}\n")
                for k in ("concentration", "latest", "horizon"):
                    if b.get(k):
                        parts.append(f"{k.capitalize()}: {b[k]}.\n")
                for e in b.get("evidence") or []:
                    parts.append(f"> {e['quote']}\n>\n")
                parts.append("\n")
        else:
            parts.append("Not an SEC registrant; no filing-based profile in this pipeline.\n\n")
        rows = [{"Indicator": reg[d["indicator"]]["name"], "Role": d["role"], "Segment": d.get("segment", ""),
                 "Expected timing": d.get("lead", ""), "Channel": d.get("why", "")} for d in c.get("drivers", [])]
        parts.append("**Operational drivers**\n\n" + md_table(pd.DataFrame(rows)) + "\n")
    (DOCS / "COMPANY_MAPPING.md").write_text("".join(parts), encoding="utf-8")


def indicators_doc() -> None:
    obs = store.load("observations", missing_ok=True)
    span = obs.groupby("series_id").agg(first=("period", "min"), last=("period", "max"), rows=("value", "size")) if not obs.empty else pd.DataFrame()
    rows = []
    for r in registry():
        sid = r["id"]
        if r["source"] == "sec_panel":
            sub = span[span.index.str.startswith(sid + ":")] if not span.empty else span
            first, last, n = (sub["first"].min(), sub["last"].max(), int(sub["rows"].sum())) if len(sub) else (None, None, 0)
        else:
            first, last, n = (span.loc[sid, "first"], span.loc[sid, "last"], int(span.loc[sid, "rows"])) if sid in span.index else (None, None, 0)
        rows.append({"id": sid, "Name": r["name"], "Source": r["source"], "Point in time": r["vintage_kind"] +
                     (f" (+{r['pub_lag_days']}d)" if r.get("pub_lag_days") else ""),
                     "Unit": r["unit"], "From": str(first.date()) if first is not None and pd.notna(first) else "no data",
                     "To": str(last.date()) if last is not None and pd.notna(last) else "", "Vintage rows": n})
    txt = GEN + "# Indicator registry\n\nEvery operational series the models may use (config/indicators.yaml), with its " \
                "coverage in the built store. 'Vintage rows' counts stored values including revisions.\n\n" + md_table(pd.DataFrame(rows))
    (DOCS / "INDICATORS.md").write_text(txt, encoding="utf-8")


def sources_table() -> None:
    src = yaml.safe_load((CONFIG / "sources.yaml").read_text(encoding="utf-8"))["sources"]
    df = pd.DataFrame([{"Source": f"[{s['name']}]({s['url']})", "Status": s["status"], "Point in time": s["vintage"],
                        "Content": s["content"], "Terms": s["terms"]} for s in src])
    (DOCS / "SOURCES_TABLE.md").write_text(GEN + md_table(df), encoding="utf-8")


def results_doc() -> None:
    def rd(name):
        p = OUT / name
        return pd.read_csv(p) if p.exists() else pd.DataFrame()
    parts = [GEN, "# Results tables\n\nAll numbers below are produced by `python scripts/run_all.py` and read from `out/`. "
             "Errors are mean absolute errors of year-over-year log revenue growth (x100 = percentage points). "
             "Periods: dev = targets 2016-2020, holdout = 2021 onward, all = both. h = 0 nowcast (one second before the "
             "release), h = 1 and h = 2 one and two quarters earlier.\n\n"]
    meta = json.loads((OUT / "backtest_meta.json").read_text()) if (OUT / "backtest_meta.json").exists() else {}
    if meta:
        parts.append(f"Panel rows: {meta['n_panel_rows']:,}; companies: {', '.join(meta['companies'])}; last target quarter {meta['last_target_quarter']}.\n\n")
    s = rd("revenue_summary.csv")
    if not s.empty:
        s["model"] = s["model"].map(lambda m: MODEL.get(m, m))
        for case in s["case"].unique():
            sub = s[s["case"] == case][["h", "period", "model", "n", "mae", "mae_vs_rw", "mae_vs_ar", "dm_p_vs_rw", "dm_p_vs_ar",
                                        "cw_p_vs_ar", "oos_r2_vs_ar", "accel_hit", "n_quarters"]].copy()
            sub["mae"] = sub["mae"] * 100
            parts.append(f"## Revenue growth, case: {case}\n\n" + md_table(sub, {"mae": "{:.2f}", "mae_vs_rw": "{:.2f}", "mae_vs_ar": "{:.2f}"}) + "\n")
    for name, title in (("margin_summary.csv", "Margins (change in gross and operating margin, pp)"),
                        ("orders_summary.csv", "Implied order intake (trailing-four-quarter growth)"),
                        ("interval_coverage.csv", "Coverage of 80% predictive intervals"),
                        ("sensitivity.csv", "Sensitivity (nowcast)"), ("returns_tests.csv", "Excess stock returns (separate question)")):
        df = rd(name)
        if not df.empty:
            if "model" in df:
                df["model"] = df["model"].map(lambda m: MODEL.get(m, m))
            parts.append(f"## {title}\n\n" + md_table(df) + "\n")
    inf = rd("inflections.csv")
    if not inf.empty:
        g = inf.groupby("ticker").agg(revenue_turns=("matched", "size"), matched=("matched", "sum"),
                                      median_lead_q=("indicator_lead_q", "median")).reset_index()
        parts.append("## Turning points in revenue growth matched by the indicator composite\n\n"
                     f"{int(inf['matched'].sum())} of {len(inf)} revenue-growth turning points had a same-direction turn in the "
                     f"company's indicator composite between 6 quarters before and 2 after (median lead "
                     f"{inf['indicator_lead_q'].median():.0f} quarters).\n\n" + md_table(g) + "\n")
    lead = rd("indicator_leads.csv")
    if not lead.empty:
        pooled = lead[lead["ticker"] == "pooled"].pivot_table(index="indicator", columns="h", values="oos_r2_vs_ar")
        pooled.columns = [f"oos_r2_h{c}" for c in pooled.columns]
        cwp = lead[lead["ticker"] == "pooled"].pivot_table(index="indicator", columns="h", values="cw_p")
        cwp.columns = [f"cw_p_h{c}" for c in cwp.columns]
        t = pooled.join(cwp).reset_index().sort_values("oos_r2_h0", ascending=False)
        parts.append("## Single-indicator tests (pooled over the companies each indicator is mapped to)\n\n"
                     "Out-of-sample R-squared of adding one indicator to the history-only model, by horizon, and the Clark-West "
                     "p-value. Positive R-squared means smaller squared errors than without the indicator.\n\n" + md_table(t) + "\n")
    (DOCS / "RESULTS.md").write_text("".join(parts), encoding="utf-8")


if __name__ == "__main__":
    DOCS.mkdir(exist_ok=True)
    company_mapping()
    indicators_doc()
    sources_table()
    results_doc()
    print("docs written")
